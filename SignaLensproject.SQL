CREATE DATABASE DashBoard;

CREATE TABLE EtlRun (
	RunId BIGINT IDENTITY(1,1) PRIMARY KEY,
	StartedAtUtc DATETIME2 NOT NULL DEFAULT GETDATE(), 
	FinishedAtUtc DATETIME2 NULL,
	Status NVARCHAR(50) NOT NULL,
	RowsLoaded INT NOT NULL,
	ErrorDetails NVARCHAR(max) NULL
);

CREATE TABLE TimeDim(
	TimeKey SMALLINT IDENTITY(1,1) PRIMARY KEY,
	Hour TINYINT NOT NULL,
	Minute TINYINT NOT NULL
);

CREATE TABLE DateDim(
--
	DateKey INT IDENTITY(1,1) PRIMARY KEY,
	FullDate DATE UNIQUE NOT NULL,
	Year SMALLINT NOT NULL,
    Month TINYINT NOT NULL,
    Day TINYINT NOT NULL,
	DayOfWeek TINYINT NOT  NULL
);

CREATE TABLE Asset(
	AssetId INT IDENTITY(1,1) PRIMARY KEY,
	AssetCode NVARCHAR(60) NOT NULL UNIQUE,
	AssetName NVARCHAR(120) NOT NULL,
	AssetType NVARCHAR(50) NOT NULL,
	Location NVARCHAR(120) NOT NULL,
	IsActive BIT NOT NULL,
	ParentAssetId INT NULL,
	--FOREIGN KEY (ParentAssetId) REFERENCES Asset(ParentAssetId)
);

CREATE TABLE Tag(
	TagId INT IDENTITY(1,1) PRIMARY KEY,
	HistorianTag NVARCHAR(180) UNIQUE NOT NULL,
	DisplayName NVARCHAR(120) NOT NULL,
	Unit NVARCHAR(30) NULL,
	ValueType NVARCHAR(20) NOT NULL,
	IsActive BIT NOT NULL,
	AssetId INT,
	FOREIGN KEY (AssetId) REFERENCES Asset(AssetId)
);

CREATE TABLE SensorReading(
	ReadingId BIGINT IDENTITY(1,1) PRIMARY KEY,
	ReadingUtc DATETIME2(7) NOT NULL,
	NumericValue FLOAT NULL,
	TextValue NVARCHAR(256) NULL,
	QualityCode INT NULL,
	SourceSampleKey NVARCHAR(200) NULL,
	TagId INT,
	DateKey INT,
	TimeKey SMALLINT,
	RunId BIGINT
	FOREIGN KEY (TagId) REFERENCES Tag(TagId),
	FOREIGN KEY (DateKey) REFERENCES DateDim(DateKey),
	FOREIGN KEY (TimeKey) REFERENCES TimeDim(TimeKey),
	FOREIGN KEY (RunId) REFERENCES EtlRun(RunId),
);

CREATE TABLE EtlWatermark(
	TagId INT IDENTITY(1,1) PRIMARY KEY,
	LastSourceUtc DATETIME2 NULL,
	SourceCursor NVARCHAR(200) NULL,
	UpdatedAtUtc DATETIME2 NOT NULL 
);



CREATE TABLE LlmProvider(
	ProviderId INT IDENTITY(1,1) PRIMARY KEY,
	Name NVARCHAR(80) UNIQUE NOT NULL,
	ModelName NVARCHAR(100) NULL,
	IsActive BIT NOT NULL
);

CREATE TABLE Users(
	UserId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(), 
	Email NVARCHAR(256) UNIQUE NOT NULL,
	DisplayName NVARCHAR(120) NOT NULL,
	Role NVARCHAR(20) NOT NULL,
	IsActive BIT NOT NULL,
	CreatedAtUtc DATETIME2 NOT NULL  DEFAULT GETDATE()
);

CREATE TABLE Dashboard(
	DashboardId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
	OwnerUserId UNIQUEIDENTIFIER NOT NULL,
	Name NVARCHAR(120) NOT NULL,
	IsDefault BIT NOT NULL,
	CreatedAtUtc DATETIME2 NOT NULL  DEFAULT GETDATE(),
	FOREIGN KEY (OwnerUserId) REFERENCES Users(UserId)
);

CREATE TABLE Widget(
	WidgetId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
	DashboardId UNIQUEIDENTIFIER NOT NULL,
	Title NVARCHAR(160) NOT NULL,
	WidgetType NVARCHAR(20) NOT NULL, 
	ChartType NVARCHAR(20) NOT NULL,
	Layoutjson NVARCHAR(MAX) NOT NULL, 
	RefreshSeconds INT NOT NULL,
	FOREIGN KEY (DashboardId) REFERENCES Dashboard(DashboardId)
);

CREATE TABLE WidgetTag(
	WidgetId UNIQUEIDENTIFIER NOT NULL,
	TagId INT NOT NULL,
	SeriesLabel NVARCHAR(120) NULL,
	Color CHAR(7),
	FOREIGN KEY (WidgetId) REFERENCES Widget(WidgetId),
	FOREIGN KEY (TagId) REFERENCES Tag(TagId),
);

